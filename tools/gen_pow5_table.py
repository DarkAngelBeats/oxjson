# include/jl_pow5.h: Eisel-Lemire 128-bit 5^q, q = -342..308 (fast_float layout).
rows = []
for q in range(-342, 0):
    power5 = 5 ** -q
    z = 0
    while (1 << z) < power5:
        z += 1
    if q >= -27:
        b = z + 127
        c = 2 ** b // power5 + 1
        rows.append(c)
    else:
        b = 2 * z + 2 * 64
        c = 2 ** b // power5 + 1
        while c >= (1 << 128):
            c //= 2
        rows.append(c)
for q in range(0, 309):
    power5 = 5 ** q
    while power5 < (1 << 127):
        power5 *= 2
    while power5 >= (1 << 128):
        power5 //= 2
    rows.append(power5)
with open('include/jl_pow5.h', 'w') as f:
    f.write('/* Generated by tools/gen_pow5_table.py: 128-bit 5^q for q = -342..308 (Eisel-Lemire). */\n')
    f.write('#define JL_POW5_QMIN (-342)\n#define JL_POW5_QMAX 308\n')
    f.write('static const unsigned long long jl_pow5[%d][2] = {\n' % len(rows))
    for c in rows:
        f.write('    {0x%016xULL, 0x%016xULL},\n' % (c >> 64, c & ((1 << 64) - 1)))
    f.write('};\n')
print(len(rows), hex(rows[342] >> 64))
