"""Generate include/json_f64_pow10.h: 128-bit significands of 10^k rounded down,
k = -293..324, normalized so the top bit is set (the table of the Zmij
algorithm, https://github.com/vitaut/zmij; MIT, see licenses/MIT-zmij.txt)."""
from pathlib import Path

K_MIN, K_MAX = -293, 324


def sig(k):
    if k >= 0:
        v = 10 ** k
        e = v.bit_length() - 128
        return v >> e if e >= 0 else v << -e
    d = 10 ** -k
    return (1 << (127 + d.bit_length())) // d


def main():
    # spot checks: 10^5 is exact; zmij stores 10^-303 rounded up before its fixups
    assert sig(5) == 0xC350000000000000 << 64
    assert sig(-303) + 1 == 0xAF8E5410288E1B6F07ECF0AE5EE44DDA
    rows = []
    for k in range(K_MIN, K_MAX + 1):
        s = sig(k)
        assert s >> 127 == 1
        rows.append("    {0x%016xULL, 0x%016xULL}, /* %d */" % (s >> 64, s & (2 ** 64 - 1), k))
    out = Path(__file__).resolve().parent.parent / "include" / "json_f64_pow10.h"
    out.write_text(
        "/* Generated by tools/gen_pow10_table.py: 128-bit significands of 10^k\n"
        " * rounded down, k = %d..%d, top bit set. */\n"
        "#ifndef JSON_F64_POW10_H\n#define JSON_F64_POW10_H\n\n#include <stdint.h>\n\n"
        "#define JZM_K_MIN (%d)\n\n"
        "static const uint64_t jzm_pow10[%d][2] __attribute__((aligned(64))) = {\n%s\n};\n\n#endif\n"
        % (K_MIN, K_MAX, K_MIN, K_MAX - K_MIN + 1, "\n".join(rows)),
        encoding="utf-8", newline="\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
